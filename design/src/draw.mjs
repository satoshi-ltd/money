export const evaluate = (file, scope = {}) => {
  const names = [...read(file).matchAll(/^export const (\w+)/gm)].map((m) => m[1]);
  const code = read(file)
    .replace(/^import .*$/gm, '')
    .replace(/^export const /gm, 'const ')
    .replace(/^export \{[^}]*\};?$/gm, '');
  const exports = {};
  new Function('exports', ...Object.keys(scope), `${code}\nObject.assign(exports, { ${names.join(', ')} });`)(
    exports,
    ...Object.values(scope),
  );
  return exports;
};

