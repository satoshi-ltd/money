export const icon = (name, { size = 'm', tone } = {}) => {
  const glyph = GLYPHS[name];
  if (!glyph) return '';
  const px = typeof size === 'number' ? size : ICON_SIZES[size];
  const colour = tone ? `color: var(--color-${kebab(tone)})` : '';
  return `<svg width="${px}" height="${px}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" style="flex-shrink:0;${colour}">${glyph.map((d) => `<path d="${d}"/>`).join('')}</svg>`;
};

