export const flowChart = ({ incomes, expenses, labels, selected, figureLabels }) => {
  const width = 350;
  const height = 132;
  const slot = width / 6;
  const baseline = height / 2;
  const peak = Math.max(...incomes, ...expenses);
  const scale = (baseline - 12) / peak;
  const median = (list) => [...list].sort((a, b) => a - b)[Math.floor(list.length / 2)];
  const bars = incomes.map((income, index) => {
    const x = index * slot + slot * 0.25;
    const w = slot * 0.5;
    const up = income * scale;
    const down = expenses[index] * scale;
    return `<rect x="${x.toFixed(1)}" y="${(baseline - up).toFixed(1)}" width="${w.toFixed(1)}" height="${up.toFixed(1)}" fill="var(--color-accent)"/><rect x="${x.toFixed(1)}" y="${baseline}" width="${w.toFixed(1)}" height="${down.toFixed(1)}" fill="var(--color-text)"/>`;
  });
  const incomeY = baseline - median(incomes) * scale;
  const expenseY = baseline + median(expenses) * scale;
  return `<div class="m-chart"><svg viewBox="0 0 ${width} ${height}" width="${width}" height="${height}"><line x1="0" x2="${width}" y1="${baseline}" y2="${baseline}" stroke="var(--color-border)"/><line x1="0" x2="${width}" y1="${incomeY.toFixed(1)}" y2="${incomeY.toFixed(1)}" stroke="var(--color-accent)" stroke-dasharray="2 3"/><line x1="0" x2="${width}" y1="${expenseY.toFixed(1)}" y2="${expenseY.toFixed(1)}" stroke="var(--color-text-muted)" stroke-dasharray="2 3"/>${bars.join('')}${selected !== undefined ? `<rect x="${(selected * slot).toFixed(1)}" y="0" width="${slot.toFixed(1)}" height="${height}" fill="var(--color-text)" opacity="0.06"/>` : ''}</svg><div class="m-axis" style="display:grid;grid-template-columns:repeat(6,1fr);text-align:center">${labels.map((label, index) => (figureLabels ? fig(label, { size: 'xs', tone: 'muted' }) : eyebrow(label, { tone: index === selected ? 'ink' : undefined }))).join('')}</div><div class="m-chart-legend"><span><i class="m-dot" style="background:var(--color-accent)"></i>${text(L.FLOW_IN, { size: 'xxs', tone: 'muted' })}</span><span><i class="m-dot" style="background:var(--color-text)"></i>${text(L.FLOW_OUT, { size: 'xxs', tone: 'muted' })}</span><span><i style="display:inline-block;width:14px;border-top:1px dashed var(--color-text-muted)"></i>${text(L.TYPICAL, { size: 'xxs', tone: 'muted' })}</span></div></div>`;
};

